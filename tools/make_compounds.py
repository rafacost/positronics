"""Write ChemLib compound formulas (atoms per compound) as a KubeJS startup global.

Positronic Memory values a compound at the sum of its atoms (projecte/emc.js), so cellulose is worth
exactly 6 C + 10 H + 5 O and splitting or combining never creates EMC. The formulas come from
ChemLib's own data/chemlib/compounds.json inside the mod jar.

Usage: python tools/make_compounds.py [path/to/chemlib.jar]
"""
import glob
import json
import os
import sys
import zipfile

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, "kubejs", "startup_scripts", "positronics", "generated", "compounds_data.js")


def find_jar():
    if len(sys.argv) > 1:
        return sys.argv[1]
    hits = glob.glob(r"D:\Minecraft\Instances\Positronics Dev\mods\chemlib-*.jar")
    if not hits:
        sys.exit("chemlib jar not found; pass its path")
    return hits[0]


def main():
    with zipfile.ZipFile(find_jar()) as z:
        data = json.loads(z.read("data/chemlib/compounds.json"))
    raw = {c["name"]: c.get("components", []) for c in data["compounds"]}

    def atoms(name, depth=0):
        if name not in raw:          # an element
            return {name: 1}
        if depth > 8:
            raise ValueError(f"compound loop at {name}")
        out = {}
        for comp in raw[name]:
            for el, n in atoms(comp["name"], depth + 1).items():
                out[el] = out.get(el, 0) + n * int(comp.get("count", 1))
        return out

    table = {name: atoms(name) for name in sorted(raw)}
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    with open(OUT, "w", encoding="utf-8", newline="\n") as f:
        f.write("// GENERATED by tools/make_compounds.py from ChemLib's compounds.json. Do not edit.\n")
        f.write("// Atoms per compound; projecte/emc.js values each compound at the sum of its atoms.\n")
        f.write("global.POSITRONICS_COMPOUNDS = " + json.dumps(table, separators=(",", ":")) + "\n")
    print(f"wrote {OUT}: {len(table)} compounds")


if __name__ == "__main__":
    main()
