"""Positronics strata generator.

Reads tools/data/strata.json and writes:
  kubejs/startup_scripts/positronics/generated/strata_data.js  (global.POSITRONICS_STRATA + EMC table)
  config/usrg-common.toml  (ore generator enabled + one weighted list per USRG tier)

If tools/data/known_items.json exists (dumped by tools/server-test.ps1), every referenced
item is validated and unknown ids are reported (and dropped from outputs).

Run:  python -I tools/make_strata.py
"""
import json
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DATA = os.path.join(ROOT, "tools", "data")


def load(path):
    with open(path, encoding="utf-8") as f:
        return json.load(f)


def main():
    strata = load(os.path.join(DATA, "strata.json"))
    known_path = os.path.join(DATA, "known_items.json")
    known = set(load(known_path)["items"]) if os.path.exists(known_path) else None
    problems = []

    def ok(item):
        if known is None or item.startswith("positronics:") or item in known:
            return True
        problems.append(item)
        return False

    tiers_out = []
    emc = {}
    for tier in strata["tiers"]:
        t = tier["tier"]
        tier_emc = strata["emc_per_tier"][str(t)]
        entries = []
        for s in tier["strata"]:
            if not ok(s["main"]):
                continue
            by = [[i, c] for i, c in s.get("by", []) if ok(i)]
            entry = {
                "id": f"positronics:{s['id']}_stratum",
                "key": s["id"],
                "name": s["name"],
                "color": int(s["color"], 16),
                "weight": s["weight"],
                "main": s["main"],
                "by": by,
            }
            for opt in ("nugget", "smelt"):
                if opt in s and ok(s[opt]):
                    entry[opt] = s[opt]
            entries.append(entry)
            # EMC: raw outputs of this tier carry the tier value (never the strata themselves).
            for item in [s["main"]] + [i for i, _ in by]:
                emc.setdefault(item, tier_emc)
                ingot = re.sub(r"_dust$", "_ingot", item)
                vanilla = {"gtceu:iron_ingot": "minecraft:iron_ingot", "gtceu:copper_ingot": "minecraft:copper_ingot",
                           "gtceu:gold_ingot": "minecraft:gold_ingot"}.get(ingot, ingot)
                if vanilla != item and (known is None or vanilla in known):
                    emc.setdefault(vanilla, tier_emc)
        tiers_out.append({"tier": t, "seed": tier["seed"], "usrg_tier": tier["usrg_tier"], "eut": tier["eut"], "strata": entries})

    trickle = [[f"positronics:{k}_stratum", c] for k, c in strata["trickle"]["chances"]]
    stages = {blk: {"hammer_tier": st["hammer_tier"], "chances": [[f"positronics:{k}_stratum", c] for k, c in st["chances"]]}
              for blk, st in strata["trickle"]["stages"].items()}

    # ---- KubeJS data (startup global, readable from server scripts too)
    js_path = os.path.join(ROOT, "kubejs", "startup_scripts", "positronics", "generated", "strata_data.js")
    os.makedirs(os.path.dirname(js_path), exist_ok=True)
    with open(js_path, "w", encoding="utf-8", newline="\n") as f:
        f.write("// priority: 1000\n")
        f.write("// GENERATED by tools/make_strata.py from tools/data/strata.json. Do not edit by hand.\n")
        f.write("global.POSITRONICS_STRATA = " + json.dumps(tiers_out, indent=2) + "\n")
        f.write("global.POSITRONICS_TRICKLE = " + json.dumps(trickle) + "\n")
        f.write("global.POSITRONICS_TRICKLE_STAGES = " + json.dumps(stages, indent=2) + "\n")
        f.write("global.POSITRONICS_EMC_VALUES = " + json.dumps(emc, indent=2, sort_keys=True) + "\n")
        caps_path = os.path.join(DATA, "star_caps.json")
        caps = load(caps_path) if os.path.exists(caps_path) else {}
        f.write("// Star capacities measured on the test server (tools/server-test.ps1).\n")
        f.write("global.POSITRONICS_STAR_CAPS = " + json.dumps(caps, indent=2, sort_keys=True) + "\n")

    # ---- USRG config: enable the ore generator and write per-tier lists
    usrg_path = os.path.join(ROOT, "config", "usrg-common.toml")
    with open(usrg_path, encoding="utf-8") as f:
        toml = f.read()
    toml = re.sub(r"oreGeneratorEnable = \w+", "oreGeneratorEnable = true", toml)
    for t in tiers_out:
        items = ", ".join(f'"{e["id"]}*{e["weight"]:.2f}"' for e in t["strata"])
        toml = re.sub(rf"oreGeneratorItemsT{t['usrg_tier']} = \[.*?\]", f"oreGeneratorItemsT{t['usrg_tier']} = [{items}]", toml, flags=re.S)
    with open(usrg_path, "w", encoding="utf-8", newline="\n") as f:
        f.write(toml)

    count = sum(len(t["strata"]) for t in tiers_out)
    print(f"strata: {count} across {len(tiers_out)} tiers; EMC values: {len(emc)}")
    print("validation:", "skipped (no known_items.json)" if known is None else (f"{len(problems)} unknown ids" if problems else "all ids known"))
    for p in sorted(set(problems)):
        print("  UNKNOWN:", p)
    return 1 if problems else 0


if __name__ == "__main__":
    sys.exit(main())
